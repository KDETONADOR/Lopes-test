let currentLang = "en";

function money(value){
  return "$" + Number(value).toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
}

function computeQuote(input){
  const sqft = input.manualSqft > 0 ? input.manualSqft : input.length * input.width;
  if (!sqft || sqft <= 0) throw new Error("INVALID_AREA");

  const base = sqft * input.serviceRate;
  let labor = base;
  const lines = [
    ["area", sqft.toFixed(1) + " sq ft"],
    ["installation", money(base)]
  ];

  if (input.prepRate > 0){
    const prep = Math.max(sqft * input.prepRate, 150);
    labor += prep;
    lines.push(["preparation", money(prep)]);
  }

  const addSqft = (enabled, key, rate) => {
    if (!enabled) return;
    const value = sqft * rate;
    labor += value;
    lines.push([key, money(value)]);
  };

  const addFlat = (enabled, key, value) => {
    if (!enabled) return;
    labor += value;
    lines.push([key, money(value)]);
  };

  addSqft(input.waterproof, "waterproof", 3.5);
  addSqft(input.demo, "demolition", 3.5);
  addSqft(input.leveling, "leveling", 2.5);

  if (input.herringbone){
    const pattern = base * 0.25;
    labor += pattern;
    lines.push(["pattern", money(pattern)]);
  }

  addFlat(input.niche, "niche", 250);
  addFlat(input.schluter, "schluter", 150);
  addFlat(input.pickup, "pickup", 125);

  if (input.miles > 10){
    const travel = (input.miles - 10) * 2;
    labor += travel;
    lines.push(["travel", money(travel)]);
  }

  const materials = Math.max(0, input.materials || 0);

  return {
    sqft,
    base,
    lines,
    labor,
    materials,
    project: labor + materials
  };
}

function num(id){
  const value = parseFloat(document.getElementById(id).value);
  return Number.isFinite(value) ? value : 0;
}

function checked(id){
  return document.getElementById(id).checked;
}

function readForm(){
  return {
    length:num("length"),
    width:num("width"),
    manualSqft:num("sqftManual"),
    serviceRate:num("service"),
    prepRate:num("prep"),
    waterproof:checked("waterproof"),
    demo:checked("demo"),
    leveling:checked("leveling"),
    herringbone:checked("herringbone"),
    niche:checked("niche"),
    schluter:checked("schluter"),
    pickup:checked("pickup"),
    miles:num("miles"),
    materials:num("materials")
  };
}

function renderQuote(){
  const error = document.getElementById("error");
  error.style.display = "none";
  error.textContent = "";

  try{
    const quote = computeQuote(readForm());
    const t = translations[currentLang];

    document.getElementById("breakdown").innerHTML = quote.lines.map(([key,value]) =>
      '<div class="breakdown-row"><span>' + t[key] + '</span><strong>' + value + '</strong></div>'
    ).join("");

    document.getElementById("laborTotal").textContent = money(quote.labor);

    const materialsWrap = document.getElementById("materialsResultWrap");
    if (quote.materials > 0){
      materialsWrap.hidden = false;
      document.getElementById("materialsTotal").textContent = money(quote.materials);
      document.getElementById("projectTotal").textContent = money(quote.project);
    } else {
      materialsWrap.hidden = true;
    }
  } catch(err){
    error.style.display = "block";
    error.textContent = translations[currentLang].inputError;
  }
}

function applyLanguage(lang){
  currentLang = lang;
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  const t = translations[lang];

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  ["service","prep"].forEach(id => {
    const select = document.getElementById(id);
    Array.from(select.options).forEach(option => {
      option.textContent = option.getAttribute("data-" + lang);
    });
  });

  const btnEN = document.getElementById("btnEN");
  const btnPT = document.getElementById("btnPT");
  btnEN.classList.toggle("active", lang === "en");
  btnPT.classList.toggle("active", lang === "pt");
  btnEN.setAttribute("aria-pressed", lang === "en" ? "true" : "false");
  btnPT.setAttribute("aria-pressed", lang === "pt" ? "true" : "false");

  renderQuote();
}

if (typeof document !== "undefined"){
  document.addEventListener("DOMContentLoaded", () => {
    document.getElementById("year").textContent = new Date().getFullYear();
    document.getElementById("calcButton").addEventListener("click", renderQuote);
    document.getElementById("btnEN").addEventListener("click", () => applyLanguage("en"));
    document.getElementById("btnPT").addEventListener("click", () => applyLanguage("pt"));

    document.querySelectorAll("#calculator input, #calculator select").forEach(el => {
      el.addEventListener("change", renderQuote);
    });

    applyLanguage("en");
  });
}

